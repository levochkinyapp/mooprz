type InteractiveMapProps = {
  /** Поиск по названиям участков на карте (data-name) */
  searchQuery?: string;
  /** Вызывается при загрузке карты с массивом названий участков (data-name) */
  onDistrictNamesLoaded?: (names: string[]) => void;
};

export default function InteractiveMap({ searchQuery = "", onDistrictNamesLoaded }: InteractiveMapProps) {
  const containerRef = useRef<HTMLDivElement>(null);
  const [svgContent, setSvgContent] = useState("");
  const [tooltip, setTooltip] = useState<{
    x: number;
    y: number;
    name: string;
  } | null>(null);
  /** Если тултип выходит за правый край экрана, задаём left вручную (слева от курсора) */
  const [tooltipLeft, setTooltipLeft] = useState<number | null>(null);
  const tooltipRef = useRef<HTMLDivElement>(null);
  const [popup, setPopup] = useState<{ name: string } | null>(null);

  const onDistrictNamesLoadedRef = useRef(onDistrictNamesLoaded);
  onDistrictNamesLoadedRef.current = onDistrictNamesLoaded;

  useEffect(() => {
    fetch("/moscow-oblast-map.svg")
      .then((r) => r.text())
      .then((html) => {
        setSvgContent(html);
        const cb = onDistrictNamesLoadedRef.current;
        if (cb) {
          const parser = new DOMParser();
          const doc = parser.parseFromString(html, "image/svg+xml");
          const paths = doc.querySelectorAll("path[data-name]");
          const names = Array.from(paths)
            .map((p) => p.getAttribute("data-name") || "")
            .filter(Boolean);
          cb(names);
        }
      });
  }, []);

  useEffect(() => {
    const el = containerRef.current;
    if (!el || !svgContent) return;

    const svg = el.querySelector("svg");
    if (!svg) return;

    svg.style.width = "100%";
    svg.style.height = "auto";
    svg.style.display = "block";

    const onMove = (e: MouseEvent) => {
      const target = (e.target as Element).closest("path[data-name]");
      if (target) {
        setTooltip({
          x: e.clientX,
          y: e.clientY,
          name: target.getAttribute("data-name") || "",
        });
      } else {
        setTooltip(null);
      }
    };

    const onLeave = () => setTooltip(null);

    const onClick = (e: MouseEvent) => {
      const target = (e.target as Element).closest("path[data-name]");
      if (target) {
        el.querySelectorAll("path.active").forEach((p) =>
          p.classList.remove("active")
        );
        target.classList.add("active");
        setPopup({ name: target.getAttribute("data-name") || "" });
      }
    };

    svg.addEventListener("mousemove", onMove);
    svg.addEventListener("mouseleave", onLeave);
    svg.addEventListener("click", onClick);

    return () => {
      svg.removeEventListener("mousemove", onMove);
      svg.removeEventListener("mouseleave", onLeave);
      svg.removeEventListener("click", onClick);
    };
  }, [svgContent]);

  // Позиция тултипа: слева от курсора, если выходит за правый край или район в списке TOOLTIP_FORCE_LEFT_NAMES
  useLayoutEffect(() => {
    if (!tooltip || !tooltipRef.current) return;
    const rect = tooltipRef.current.getBoundingClientRect();
    const padding = 8;
    const forceLeft = TOOLTIP_FORCE_LEFT_NAMES.has(tooltip.name);
    const overflowsRight = rect.right > window.innerWidth - padding;
    if (forceLeft || overflowsRight) {
      setTooltipLeft(Math.max(padding, tooltip.x - rect.width - 14));
    } else {
      setTooltipLeft(null);
    }
  }, [tooltip]);

  // Подсветка/затемнение участков по поисковому запросу
  useEffect(() => {
    const el = containerRef.current;
    if (!el) return;

    const paths = el.querySelectorAll<SVGPathElement>("path[data-name]");
    const query = searchQuery.toLowerCase().trim();

    paths.forEach((path) => {
      path.classList.remove(SEARCH_MATCH_CLASS, SEARCH_MISMATCH_CLASS);
      if (!query) return;

      const name = (path.getAttribute("data-name") || "").toLowerCase();
      const matches = name.includes(query);
      path.classList.add(matches ? SEARCH_MATCH_CLASS : SEARCH_MISMATCH_CLASS);
    });
  }, [svgContent, searchQuery]);

  const closePopup = () => {
    setPopup(null);
    containerRef.current
      ?.querySelectorAll("path.active")
      .forEach((p) => p.classList.remove("active"));
  };

  const tooltipEl = tooltip && (
    <div
      ref={tooltipRef}
      className="fixed z-40 px-3 py-1.5 rounded bg-[#003366] text-white text-sm font-medium shadow-lg pointer-events-none whitespace-nowrap"
      style={{
        left: tooltipLeft ?? tooltip.x + 14,
        top: tooltip.y - 36,
      }}
    >
      {tooltip.name}
    </div>
  );

  return (
    <>
      <div
        ref={containerRef}
        className="relative w-full max-w-3xl mx-auto"
        dangerouslySetInnerHTML={{ __html: svgContent }}
      />

      {tooltipEl && createPortal(tooltipEl, document.body)}

      <ModalOverlay
        open={!!popup}
        onClose={closePopup}
        ariaLabel={popup ? (DISTRICT_POPUP_CONTENT[popup.name]?.title ?? popup.name) : undefined}
      >
        {popup && (
          <>
            <h3 className="text-lg font-bold text-[#003366] mb-1">
              {DISTRICT_POPUP_CONTENT[popup.name]?.title ?? popup.name}
            </h3>
            <p className="text-sm text-gray-600 mb-4">
              {DISTRICT_POPUP_CONTENT[popup.name]?.text ??
                "Организации профсоюза работников здравоохранения"}
            </p>
            {DISTRICT_POPUP_CONTENT[popup.name]?.subOrgs?.map((org, index) => (
              <div key={index} className="pl-4 mt-3 border-l-2 border-primary/30">
                <h4 className="text-base font-semibold text-[#003366] mb-0.5">
                  {org.title}
                </h4>
                <p className="text-sm text-gray-600">{org.text}</p>
              </div>
            ))}
          </>
        )}
      </ModalOverlay>
    </>
  );
}
